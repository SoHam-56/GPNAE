    total_checks = sum(a["total"] for r in results for a in r["per_act"].values())
    total_fail = sum(a["failed"] + a["missing"] for r in results for a in r["per_act"].values())
    worst = max((a["worst"] for r in results for a in r["per_act"].values()), default=0.0)

    W = 100
    L = []
    L.append("=" * W)
    L.append("GPNAE — ACTIVATION REGRESSION REPORT")
    L.append("=" * W)
    L.append("")
    L.append(f"Date              : {datetime.now().strftime('%Y-%m-%d %H:%M')}")
    L.append(f"Format            : {fmt.name}  {fmt.width} bits "
             f"(1 sign + {fmt.exp_bits} exp + {fmt.man_bits} mantissa), eps {fmt.eps:.3e}")
    L.append(f"Volume            : {batches} batches x {per_batch} signals = "
             f"{batches*per_batch} per activation")
    L.append(f"Element checks    : {total_checks}")
    L.append(f"Reference model   : {model}")
    L.append(f"Seed              : {seed}")
    L.append(f"Stimulus ranges   : " + ", ".join(f"{a} +/-{r}" for a, r in ranges.items()))
    L.append(f"Tolerance         : relative <= {suggested_rel_tol(fmt)*100:.4f}% "
             f"or absolute <= {abs_tol:g} (either bound passes)")
    L.append("")
    L.append(f"RESULT            : {'PASS' if n_pass == len(results) else 'FAIL'}  "
             f"({n_pass}/{len(results)} patterns, {total_fail} element failures)")
    L.append(f"Worst rel error   : {worst:.4f}%")
    L.append("")
    L.append("-" * W)
    L.append("PER-PATTERN RESULTS")
    L.append("-" * W)
    L.append(f"{'pattern':<18}{'activation':<11}{'n':>6}{'exact':>9}{'tol':>9}"
             f"{'failed':>8}{'missing':>9}{'worst err':>12}{'mean err':>12}")
    L.append("-" * W)
    for r in results:
        for act, a in r["per_act"].items():
            tot = max(a["total"], 1)
            L.append(f"{r['name']:<18}{act:<11}{a['total']:>6}"
                     f"{100*a['exact']/tot:>8.1f}%{100*a['tol']/tot:>8.1f}%"
                     f"{a['failed']:>8}{a['missing']:>9}"
                     f"{a['worst']:>11.4f}%{a['mean']:>11.4f}%")
        L.append("")
    L.append("-" * W)
    L.append("NOTES")
    L.append("-" * W)
    L.append("* The FP units truncate rather than round and the activation is a finite")
    L.append("  polynomial, so exact matches are the exception. Tolerance passes are the")
    L.append("  normal case and are not a defect.")
    L.append("* Two lanes exist and they are NOT numerically equivalent:")
    L.append("    gpnae       evaluates e^x by Maclaurin series, then reshapes it")
    L.append("                (divider for sigmoid and tanh). terms_i trades accuracy")
    L.append("                against speed. Qualify with --model series or --model exact.")
    L.append("    gpnae_poly  fits each activation directly, so there is no exponential")
    L.append("                and no divider. terms_i is inert: truncating a fitted")
    L.append("                polynomial is meaningless. Qualify with --model exact ONLY;")
    L.append("                --model series describes a route this lane does not take.")
    L.append("* --model exact  compares against true mathematics, i.e. what a framework")
    L.append("                 such as TensorFlow produces. Use it to qualify either lane.")
    L.append("* --model series compares against the finite series the MAC evaluates, with")
    L.append("                 every intermediate quantised and truncated as the hardware")
    L.append("                 does. Use it on the gpnae lane to separate an RTL fault")
    L.append("                 from series truncation or format precision.")
    L.append("* Stimulus ranges come from `python3 gpnae_tests.py --accuracy`, which shows")
    L.append("  where each term count stops tracking the true function for this format.")
    L.append("* `python3 number_formats.py --rtl` lists the RTL files that must be swapped")
    L.append("  or parameterised to retarget the block to another number format.")
    L.append("=" * W)
    with open(path, "w") as f:
        f.write("\n".join(L) + "\n")
    return path


