def write_config(fmt, batches: int, per_batch: int, rel_tol: float, abs_tol: float,
                 model: str, timeout_cycles: int, seed: int, exact: bool = False,
                 coeff_file: str = "poly_coeffs.mem", req_rounding: str = None) -> None:
    """Emit the include file the testbench pulls in."""
    path = os.path.join(TB_DIR, "gpnae_test_config.svh")
    with open(path, "w") as f:
        # No timestamp: this file is tracked, and a timestamp would leave the tree dirty after every run.
        f.write("// Auto-generated by regression.py -- do not edit by hand.\n\n")
        f.write(f"  localparam int DATA_WIDTH       = {fmt.width};\n")
        f.write(f"  localparam int EXP_BITS         = {fmt.exp_bits};\n")
        f.write(f"  localparam int MAN_BITS         = {fmt.man_bits};\n")
        f.write(f'  localparam string FMT_NAME      = "{fmt.name}";\n')
        f.write(f"  localparam int NUM_BATCHES      = {batches};\n")
        f.write(f"  localparam int SIGNALS_PER_BATCH = {per_batch};\n")
        f.write(f"  localparam int SELU_TERMS       = {ACTIVATIONS['selu']['terms']};\n")
        f.write(f"  localparam int SIGMOID_TERMS    = {ACTIVATIONS['sigmoid']['terms']};\n")
        f.write(f"  localparam int TANH_TERMS       = {ACTIVATIONS['tanh']['terms']};\n")
        f.write(f"  localparam real REL_TOL         = {rel_tol};\n")
        f.write(f"  localparam real ABS_TOL         = {abs_tol};\n")
        f.write(f"  localparam int TIMEOUT_CYCLES   = {timeout_cycles};\n")
        f.write(f"  localparam int SEED             = {seed};\n")
        f.write(f'  localparam string REF_MODEL     = "{model}";\n')
        f.write('  localparam string STIM_DIR      = "testbenches/stimulus/";\n')
        f.write(f"  localparam bit EXACT_MATCH      = {1 if exact else 0};\n")
        f.write(f'  localparam string COEFF_FILE    = "{coeff_file}";\n')
        if req_rounding is None:
            import gpnae_model
            req_rounding = gpnae_model.REQ_ROUNDING  # the rounding the model's SELU requantize uses, from sienna_fmt_pkg
        f.write(f'  localparam string REQ_ROUNDING  = "{req_rounding}";\n')


def generate_vectors(test_name: str, fmt, batches: int, per_batch: int, model: str,
                     seed: int, range_override: float = None) -> dict:
    """Write <act>_in.mem and <act>_exp.mem for all three activations."""
    os.makedirs(STIM_DIR, exist_ok=True)
    test = get_test(test_name)
    ranges = {}
    for act, cfg in ACTIVATIONS.items():
        rmax = range_override if range_override is not None else cfg["default_range"]
        stim = []
        for b in range(batches):
            rs = np.random.RandomState(seed + 1013 * b + 7919 * ACTIVATIONS[act]["code"])
            # Bound is swept, not random: batch b gets (b+1)/batches of rmax, so the last batch reaches full range.
            # Drawing it randomly let every batch fall short of large |x| and hid a known defect.
            # act_sweep and act_edge keep the full bound; act_edge places +/-rng literally, so it is the reproducer.
            if test["name"] in ("act_sweep", "act_edge"):
                rng = rmax
            else:
                frac = (b + 1) / batches
                rng = rmax * min(1.0, frac * rs.uniform(0.85, 1.15))
            stim.extend(test["gen_fn"](act, per_batch, rng, fmt, rs))
        gold = golden(stim, act, model, fmt)
        write_mem(os.path.join(STIM_DIR, f"{act}_in.mem"), stim, fmt)
        write_mem(os.path.join(STIM_DIR, f"{act}_exp.mem"), gold, fmt)
        ranges[act] = rmax
    return ranges


