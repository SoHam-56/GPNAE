STREAM_BYP = ((0, 20), (0, 17), (0, 1), (0, 16), (2, 8), (1, 16), (1, 5), (1, 1), (1, 32), (0, 32), (1, 2), (0, 16),
              (2, 1))  # ReLU and linear emit 16 cycles after capture, so a busy group is at most 8
S_IDLE, S_NEXT, LANE_K = 0, 8, 16  # gpnae_poly_int8's G_IDLE and G_NEXT encodings, and its group size


def rand_params_int8(rng, code, sat):
    """A random lane parameter set; sat makes mx / 2^shx >= 256, so inputs with |q - z_in| >= 128 saturate Q4.11."""
    import gpnae_model as gm
    mx = int(rng.integers(1 << 14, 1 << 15)) if sat else int(rng.integers(0, 1 << 15))
    shx = int(rng.integers(0, 7)) if sat else int(rng.integers(8, 21))  # shx >= 8 keeps 255 * mx / 2^shx below 2^15
    zin = int(rng.integers(-128, 128))
    if code == 1:  # any normalized multiplier; SELU's shift is <= 0 by the host's contract
        return gm.Int8Params(mx, shx, zin, int(rng.integers(1 << 30, 1 << 31)), int(rng.integers(-31, 1)),
                             int(rng.integers(-128, 128)))
    return gm.Int8Params(mx, shx, zin, 0, 0, 0)


def large_case(rng, k):
    """Large-scale SELU set k: z_in -128, s_in log-spaced 1 to 15.99, x to 255 s_in; s_out calibrated on that range (odd k) or a random part of it (even k, the top clamps)."""
    import gpnae_model as gm
    s_in = float(np.geomspace(1.0, 15.99, N_LARGE_INT8)[k])
    s_out, z_out = gm.calib_out(0.0, gm.LAMBDA_F * 255 * s_in * (1.0 if k % 2 else float(rng.uniform(0.25, 1.0))))
    return gm.Case(s_in, -128, s_out, z_out, True)


def fine_case(rng, k):
    """Fine-scale SELU set k: s_in log-spaced 1e-7 to 1e-2, z_in random, s_out calibrated on the input's whole range (selu_case)."""
    import gpnae_model as gm
    return gm.selu_case(float(np.geomspace(1e-7, 1e-2, N_FINE_INT8)[k]), int(rng.integers(-128, 128)))


def ladder_hit(x):
    """(mx, shx, d): with z_in = 0, input d rescales to x and input -d to -x exactly, d in 1..127."""
    for shx in range(15, -1, -1):
        h = (1 << shx) >> 1
        for d in range(127, 0, -1):
            mx = -(-(x * (1 << shx) - h) // d)  # the smallest mx whose rounded rescale of d reaches x
            if mx <= 32767 and (d * mx + h) >> shx == x and (-d * mx + h) >> shx == -x:
                return mx, shx, d
    raise ValueError(f"no int8 input pair rescales to +-{x}")


def ladder_xs():
    """The Q4.11 value each ladder edge set lands a code on (and its negation), then -32768 for the saturating set."""
    import gpnae_model as gm
    return [v for t in gm.SIG_LAD_T for v in (t - 1, t)] + [gm.SIG_LAD_X0 - 1, gm.SIG_LAD_X0, -32768]


def ladder_sets():
    """Two rescales per threshold (codes t_i - 1 and t_i, both signs), the hand-over 5119 and 5120, and q = -128 at x = -32768."""
    import gpnae_model as gm
    return [gm.Int8Params(*ladder_hit(x)[:2], 0, 0, 0, 0) for x in ladder_xs()[:-1]] + [gm.Int8Params(32767, 0, 0, 0, 0, 0)]


def sweep_sets(rng):
    """The scale sweep: 64 rescales, s_in log-spaced from 1/128 to 1/8, z_in random in [-64, 64]."""
    import gpnae_model as gm
    return [gm.Int8Params(*gm.rescale_params(float(s)), int(rng.integers(-64, 65)), 0, 0, 0) for s in np.geomspace(1 / 128, 1 / 8, N_SWEEP_INT8)]


def rescale_saturates(p) -> bool:
    """Whether some int8 input's rescale leaves Q4.11 before the clip."""
    q = np.arange(-128, 128, dtype=np.int64)
    raw = (q - p.zin) * p.mx
    raw = raw if p.shx == 0 else (raw + (1 << (p.shx - 1))) >> p.shx
    return bool(((raw > 32767) | (raw < -32768)).any())


def stream_starts(mode, n):
    """The group starts one stream group should produce, as (state it starts from, size)."""
    if mode == 2:
        first, via = min(LANE_K, n), S_NEXT  # queued while the lane works: G_NEXT takes it
    else:
        first, via = min(LANE_K, n), S_IDLE  # G_IDLE starts it at its last put, held back or not
    out, left = [(via, first)], n - first
    while left:
        out.append((S_NEXT, min(LANE_K, left)))  # the rest is already queued: G_NEXT takes it, 16 at a time
        left -= out[-1][1]
    return out


def write_stream_int8(lane, rng) -> dict:
    """stream_*.mem for TB_gpnae_poly's protocol edges: every control word, a gated case and a saturating random set each."""
    import gpnae_model as gm
    segs = []
    for act, code in INT8_ACTS:
        segs.append((code, gm.int8_params(gm.INT8_CASES[act][0], code), gm.INT8_CASES[act][0]))
        if code <= 3:
            segs.append((code, rand_params_int8(rng, code, True), None))
    tc = gm.INT8_CASES["tanh"][1]
    segs += [(cw, gm.int8_params(tc, 3), tc) for cw in (0, 6, 7)]  # every other control word runs tanh
    seg_l, grp_l, bnd, q_all, y_all, funcs, quants = [], [], [], [], [], [], []
    for cw, p, case in segs:
        script = STREAM_BYP if cw in (4, 5) else STREAM_POLY
        n_el = sum(n for _, n in script)
        q = np.concatenate([rng.permutation(256) for _ in range(-(-n_el // 256))]).astype(np.int64)[:n_el] - 128
        q_all += [int(v) for v in q]
        y_all += [int(v) for v in lane.run(q, cw, p)]
        code = cw if cw in (1, 2, 4, 5) else 3
        funcs += [INT8_ACTS[code - 1][0]] * n_el
        quants += [int8_quant(code, case, p)] * n_el  # the element's function and scales, for the truth gate
        seg_l.append(f"{cw:02x}{len(script):02x}{p.mx:04x}{p.shx:02x}{p.zin & 0xFF:02x}{p.mout:08x}{p.shout & 0xFF:02x}"
                     f"{p.zout & 0xFF:02x}\n")
        for mode, n in script:
            grp_l.append(f"{mode:02x}{n:02x}{len(bnd):04x}\n")
            bnd += stream_starts(mode, n)
    files = {"stream_seg.mem": seg_l, "stream_grp.mem": grp_l,
             "stream_in.mem": [f"{v & 0xFF:02x}\n" for v in q_all], "stream_exp.mem": [f"{v & 0xFF:02x}\n" for v in y_all],
             "stream_bnd.mem": [f"{v:02x}{s:02x}\n" for v, s in bnd],
             "stream_cnt.mem": [f"{v:08x}\n" for v in (len(seg_l), len(grp_l), len(q_all), len(bnd))]}
    for name, lines in files.items():
        with open(os.path.join(STIM_DIR, name), "w") as fh:
            fh.write("".join(lines))
    return {"segments": len(seg_l), "groups": len(grp_l), "elements": len(q_all), "starts": len(bnd), "q": np.array(q_all),
            "func": np.array(funcs), "quant": [np.array([x[k] for x in quants]) for k in range(4)]}


def truth_stream(stream, got) -> tuple:
    """The gate on the protocol stream's RTL words (stream_got.mem), per function: (results, lines); None where the words are missing."""
    res, lines = {}, []
    for act, _ in INT8_ACTS:
        m = stream["func"] == act
        if got is None:
            res[act] = None
            continue
        r = truth.gate("int8", act, stream["q"][m], got[m], quant=[v[m] for v in stream["quant"]])
        lines.append(f"  stream   {truth.line(r)}")
        print(f"        stream   {'PASS' if r.ok else 'FAIL'}  n {r.n}  worst {truth.worst_text(r.worst)} ({r.worst_lsb} LSB)  "
              f"over {100 * truth.BOUND:g}%: {r.over}  over {100 * truth.TARGET:g}%: {r.over_target}  ({act})")
        res[act] = r
    return res, lines


def int8_sets(seed) -> dict:
    """Every lane parameter set run_int8 drives, per activation in stimulus order: (kind, case or None, params, the 256 inputs)."""
    import gpnae_model as gm
    lad_sets, sweep = ladder_sets(), sweep_sets(np.random.default_rng([seed, 16]))
    rl = np.random.default_rng([seed, 15])  # their input order: a new stream, so the earlier sets' stimulus is unchanged
    extra_q = [rl.permutation(256).astype(np.int64) - 128 for _ in range(N_LAD_INT8 + N_SWEEP_INT8)]
    rs = np.random.RandomState(seed)
    rr = np.random.default_rng([seed, 12])  # the random parameter sets and their input order
    rp = np.random.default_rng([seed, 14])  # the large-scale sets and their input order
    large = [large_case(rp, k) for k in range(N_LARGE_INT8)]  # every activation runs SELU's scales; only SELU's outputs are of interest
    large_q = [rp.permutation(256).astype(np.int64) - 128 for _ in large]
    rf = np.random.default_rng([seed, 17])  # the fine-scale and edge sets and their input order
    fine = [fine_case(rf, k) for k in range(N_FINE_INT8)] + [gm.Case(*e, True) for e in EDGE_SELU]
    fine_q = [rf.permutation(256).astype(np.int64) - 128 for _ in fine]
    out = {}
    for act, code in INT8_ACTS:
        sets = []
        for case in gm.INT8_CASES[act]:
            sets.append(("case", case, gm.int8_params(case, code), rs.permutation(256).astype(np.int64) - 128))  # every input once
        rand = [rand_params_int8(rr, code, k < N_SAT_INT8) for k in range(N_RAND_INT8)]
        sets += [("random", None, p, rr.permutation(256).astype(np.int64) - 128) for p in rand]
        own = (lambda c: c) if code == 1 else (lambda c: None)  # SELU gates on the set's float scales; the others on what the rescale encodes
        sets += [("large", own(c), gm.int8_params(c, code), q) for c, q in zip(large, large_q)]
        sets += [("ladder" if k < N_LAD_INT8 else "sweep", None, p, q) for k, (p, q) in enumerate(zip(lad_sets + sweep, extra_q))]
        sets += [("fine" if k < N_FINE_INT8 else "edge", own(c), gm.int8_params(c, code), q) for k, (c, q) in enumerate(zip(fine, fine_q))]
        out[act] = sets
    assert len(lad_sets) == N_LAD_INT8
    return out


INT8_OUT = {2: (1 / 256, -128), 3: (1 / 128, 0)}  # sigmoid's and tanh's fixed output quantization (TFLite's)


def int8_quant(code, case, p):
    """(s_in, z_in, s_out, z_out) of a set: a case's own float scales; otherwise the scales its integers encode."""
    if case is not None:
        return case.s_in, case.z_in, case.s_out, case.z_out
    s_in = p.mx * 2.0 ** -p.shx / 2048  # the rescale: x = (q - z_in) mx / 2^shx in Q4.11
    if code == 1:  # requantize: q = acc mout 2^(shout - 31), acc = x 2^(shx + 18), x = (q - z_in) s_in, s_in = mx 2^-(shx + 11)
        s_out = s_in * 2.0 ** (24 - p.shout) / (p.mx * p.mout) if p.mout and p.mx else np.inf
        return s_in, p.zin, s_out, p.zout  # a zero multiplier (the ladder and sweep sets) leaves only the zero point
    if code in INT8_OUT:
        return (s_in, p.zin) + INT8_OUT[code]
    return s_in, p.zin, s_in, p.zin  # ReLU and linear pass the code through


def truth_int8(sets, gots) -> tuple:
    """The gate on each activation's RTL words over every set and every input; ReLU below z_in must give the output zero point."""
    res, lines = {}, []
    for act, code in INT8_ACTS:
        got = gots[act]
        if got is None:
            res[act] = None
            continue
        rows = [(kind, q, int8_quant(code, case, p)) for kind, case, p, q in sets[act]]
        q = np.concatenate([r[1] for r in rows])
        quant = [np.repeat([r[2][k] for r in rows], 256) for k in range(4)]
        kinds = np.repeat([r[0] for r in rows], 256)
        r = truth.gate("int8", act, q, got, quant=quant)
        lines.append(show_truth(r))
        for kind in dict.fromkeys(kinds):
            m = kinds == kind
            rk = truth.gate("int8", act, q[m], got[m], quant=[v[m] for v in quant])
            lines.append(f"  {kind:<9}{truth.line(rk)}")
            print(f"        {kind:<9}{'PASS' if rk.ok else 'FAIL'}  n {rk.n}  worst {100 * rk.worst:.3f}% ({rk.worst_lsb} LSB)  "
                  f"over {100 * truth.BOUND:g}%: {rk.over}  over {100 * truth.TARGET:g}%: {rk.over_target}")
        res[act] = r
    return res, lines


