def run_make(lane: str = "gpnae") -> tuple:
    """Build and run via the project Makefile."""
    t0 = time.time()
    cmd = ["make", "verilator"]
    if lane == "poly":
        cmd += ["TESTBENCH=TB_gpnae_poly.sv", "TOP_MODULE=TB_gpnae_poly"]
    if os.environ.get("GPNAE_PIN", "0") == "1" and shutil.which("taskset"):
        cmd = ["taskset", "-c", "0"] + cmd
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    return r.stdout + r.stderr, time.time() - t0


def parse_log(raw: str, expect_total: int = 0, expect_acts: int = 3) -> dict:
    """Pull the per-activation RESULT/CYCLES lines and the overall verdict."""
    per_act = {}
    for m in re.finditer(
            r"RESULT (\w+) : total (\d+)\s+exact (\d+)\s+tol (\d+)\s+failed (\d+)\s+missing (\d+)",
            raw):
        act, tot, ex, tol, fail, miss = m.groups()
        per_act[act] = dict(total=int(tot), exact=int(ex), tol=int(tol),
                            failed=int(fail), missing=int(miss), cycles=0,
                            worst=0.0, mean=0.0)
    for m in re.finditer(r"CYCLES (\w+) :.*?per-input (\d+)", raw):
        act, cyc = m.groups()
        if act in per_act:
            per_act[act]["cycles"] = int(cyc)
    for m in re.finditer(r"ERRSTAT (\w+) : worst ([\d.]+)%\s+mean ([\d.]+)%", raw):
        act, worst, mean = m.groups()
        if act in per_act:
            per_act[act]["worst"] = float(worst)
            per_act[act]["mean"] = float(mean)

    passed = "RESULT: PASSED" in raw
    if not per_act and ("%Error" in raw or "Error" in raw):
        return dict(status="BUILD-ERROR", per_act={}, failed=1)
    total_failed = sum(a["failed"] + a["missing"] for a in per_act.values())

    # "Zero failures" only means something once the expected checks actually ran. A build that
    # does not launch, or a testbench that silently checks a handful of elements, otherwise
    # reads as a clean pass -- which has happened more than once in this repo.
    short = []
    if len(per_act) != expect_acts:
        short.append(f"{len(per_act)} of {expect_acts} activations reported")
    if expect_total:
        for act, a in sorted(per_act.items()):
            if a["total"] != expect_total:
                short.append(f"{act} checked {a['total']} of {expect_total}")

    if short:
        return dict(status="NO-RESULTS", per_act=per_act, failed=max(1, total_failed),
                    short=short)
    return dict(status="PASS" if (passed and total_failed == 0) else "FAIL",
                per_act=per_act, failed=total_failed, short=[])


def print_activation(act: str, r: dict) -> None:
    tot = max(r["total"], 1)
    sym = ok("PASS") if (r["failed"] + r["missing"]) == 0 else err("FAIL")
    print(f"      {sym}  {act:<8} n {r['total']:5d}  exact {100*r['exact']/tot:5.1f}%  "
          f"tol {100*r['tol']/tot:5.1f}%  fail {r['failed']:4d}  miss {r['missing']:3d}  "
          f"err worst {r['worst']:7.4f}% mean {r['mean']:7.4f}%  {r['cycles']:4d} cyc/in")


